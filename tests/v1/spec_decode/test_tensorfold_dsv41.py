"""Compare algorithm behavior to executions of the pinned TensorFold Zig source.

The leaf owns no GPU/model state. Its observable contracts are row admission,
matched prefixes and copied continuations. The fixtures were generated by the
locked source oracle, not by this Python implementation. Model integration is
validated separately through real OpenAI requests before any performance run.
"""

import json
import runpy
import struct
from pathlib import Path

import pytest

ROOT = Path(__file__).parents[3]
core = runpy.run_path(
    str(ROOT / "vllm/v1/worker/gpu/spec_decode/tensorfold_dsv41/core.py")
)
sampling = runpy.run_path(
    str(ROOT / "vllm/v1/worker/gpu/spec_decode/tensorfold_dsv41/sampling.py")
)
DATA = Path(__file__).parent / "data/tensorfold_dsv41"
inputs = [json.loads(x) for x in (DATA / "input.jsonl").read_text().splitlines()]
expected = [json.loads(x) for x in (DATA / "expected.jsonl").read_text().splitlines()]


@pytest.mark.parametrize("streams", [2, 4, 8])
def test_multilane_joint_budget_and_copy_reservation(streams):
    rule = core["MultiLaneRule"]()
    lanes = [core["CalibratedLaneState"]() for _ in range(streams)]
    entries = [(1, lane, [2.0] * 5, 0) for lane in lanes]
    entries[0] = (1, lanes[0], [], 5)
    grants = rule.admit_batch(entries, 6 * streams)
    assert grants[0] == 5
    assert all(0 <= grant <= 5 for grant in grants)
    assert sum(grants) + streams <= 6 * streams
    # Reserving copies must not mistake their rows for spare head capacity.
    assert rule.admit_batch(entries, streams + 5) == [5] + [0] * (streams - 1)


def test_multilane_prefers_confident_prefix_under_shared_budget():
    rule = core["MultiLaneRule"]()
    lanes = [core["CalibratedLaneState"]() for _ in range(2)]
    entries = [(1, lanes[0], [-20.0] * 5, 0), (1, lanes[1], [20.0] * 5, 0)]
    assert rule.admit_batch(entries, 5) == [0, 3]


def test_multilane_preserves_single_lane_decisions():
    for logits in ([0.0] * 5, [3.0, 2.0, 1.0, 0.0, -1.0], [-20.0] * 5):
        lane = core["CalibratedLaneState"]()
        expected = core["CalibratedLaneRule"]().admit(lane, logits, room=6)
        assert core["MultiLaneRule"]().admit_batch([(1, lane, logits, 0)], 6) == [
            expected
        ]


def test_multilane_state_isolation_after_slot_replacement():
    lanes = {req: core["CalibratedLaneState"]() for req in ("a", "b")}
    lanes["a"].observe_confidence([0.0] * 5, 5, 3)
    lanes["a"].context.extend([11, 12])
    assert lanes["b"].context == [] and lanes["b"].trials == [0] * 5
    del lanes["a"]
    lanes["replacement"] = core["CalibratedLaneState"]()
    assert lanes["replacement"].context == []
    assert lanes["replacement"].residual == [0.0] * 5


@pytest.mark.parametrize("streams", [2, 4, 8])
def test_graph_uniform_prefix_matches_complete_rate_search(streams):
    rule = core["MultiLaneRule"]()
    lanes = [core["CalibratedLaneState"]() for _ in range(streams)]
    entries = [(1, lane, [2.0, 1.0, 0.0, -1.0, -2.0], 0) for lane in lanes]
    entries[0] = (1, lanes[0], [], 3)
    probs = [[1.0] * 3] + [core["survivals"](e[2]) for e in entries[1:]]
    costs = dict(rule.costs)
    for rows in range(25, 49):
        costs[rows] = costs[24] + (costs[24] - costs[23]) * (rows - 24)
    rates = [
        (streams + sum(sum(p[:k]) for p in probs)) / (costs[streams * (k + 1)] + 8)
        for k in range(4)
    ]
    expected = max(range(4), key=rates.__getitem__)
    assert rule.admit_uniform(entries, streams * 6) == [expected] * streams


def test_graph_uniform_handles_missing_and_unconfident_prefixes():
    rule = core["MultiLaneRule"]()
    lane = core["CalibratedLaneState"]()
    assert rule.admit_uniform([(1, lane, [], 0), (1, lane, [20.0] * 5, 0)], 12) == [
        0,
        0,
    ]
    assert rule.admit_uniform([(1, lane, [-20.0] * 5, 0)] * 2, 12) == [0, 0]
    with pytest.raises(ValueError, match="one anchor"):
        rule.admit_uniform([(2, lane, [20.0] * 5, 0)], 6)


def test_runtime_calibration_starts_with_original_admission():
    """A new request has no calibration history from warmup or other requests."""
    lane = core["CalibratedLaneState"]()
    logits = [1.3, 0.7, 0.2, -0.4, -1.0]
    assert lane.calibrated_survivals(logits) == core["survivals"](logits)
    assert core["CalibratedLaneRule"]().admit(lane, logits) == core["LaneRule"]().admit(
        core["LaneState"](), logits
    )


def test_runtime_calibration_observes_only_reached_head_positions():
    """Rejected descendants are unobserved, not five independent failures."""
    lane = core["CalibratedLaneState"]()
    lane.observe_confidence([0.0] * 5, drafts=5, accepted=2)
    assert lane.trials == [1, 1, 1, 0, 0]
    assert lane.residual == [0.5, 0.5, -0.5, 0.0, 0.0]


def test_runtime_calibration_corrects_bias_without_cross_request_state():
    """Underconfident heads earn deeper offers; overconfident heads back off."""
    high, low = core["CalibratedLaneState"](), core["CalibratedLaneState"]()
    logits = [0.5] * 5
    for _ in range(100):
        high.observe_confidence(logits, 5, 5)
        low.observe_confidence(logits, 5, 0)
    rule = core["CalibratedLaneRule"]()
    fresh = core["CalibratedLaneState"]()
    assert rule.admit(high, logits) > rule.admit(fresh, logits)
    assert rule.admit(low, logits) < rule.admit(fresh, logits)
    assert fresh.trials == [0] * 5


def test_runtime_calibration_zero_admission_can_recover_on_new_confidence():
    """A run of failed drafts can back off to zero without a permanent disable."""
    lane = core["CalibratedLaneState"]()
    for _ in range(100):
        lane.observe_confidence([-1.0] * 5, 1, 0)
    rule = core["CalibratedLaneRule"]()
    assert rule.admit(lane, [-1.0] * 5) == 0
    assert rule.admit(lane, [4.0] * 5) > 0


@pytest.mark.parametrize("case,want", list(zip(inputs, expected, strict=True)))
def test_matches_locked_tensorfold_executable(case, want):
    """Admission ties, zero budget, rejected prefixes and suffix matching."""
    got = core["allocate"](
        case["fixed"],
        case["probs"],
        dict(enumerate(case["costs"], 1)),
        case["overhead"],
        case["max_rows"],
    )
    assert got == want["depths"]
    committed, accepted = core["accept_chain"](case["drafts"], case["picks"])
    assert list(range(accepted + 1)) == want["path"]
    assert committed == case["drafts"][:accepted] + [case["picks"][accepted]]
    proposer = core["SuffixLookup"]()
    assert proposer.propose(case["context"], 15) == want["copy"]
    assert proposer.last_match == want["last_match"]
    ordered = sorted(enumerate(case["row"]), key=lambda x: (-x[1], x[0]))
    assert (
        sampling["choose"](
            [v for _, v in ordered],
            [i for i, _ in ordered],
            **{
                k: case[k]
                for k in ("seed", "position", "temperature", "top_k", "top_p", "min_p")
            },
        )
        == want["sample"]
    )


@pytest.mark.parametrize(
    "seed,pos,token,bits",
    [
        (101, 2229, 2581, 0x3FE8CD8867D6A69C),
        (404, 59, 129279, 0x3FD08F785F86DA1B),
        (0, 0, 0, 0x3FC9FF45EA7CE2BE),
    ],
)
def test_keyed_random_bits_match_tensorfold(seed, pos, token, bits):
    value = sampling["uniform"](seed, pos, token)
    assert struct.unpack("<Q", struct.pack("<d", value))[0] == bits


def test_c1_drafts_full_head_even_after_zero_admission():
    """Native C1 uses headDepth directly; granted+slack only bounds shared runs."""
    lane = core["LaneState"](granted=0)
    assert lane.head_depth(False) == 5
    assert lane.head_depth(False, shared=True) == 2
    assert lane.head_depth(True) == 1


def test_copy_rejections_silence_then_allow_the_proposer_again():
    """Four zero-accept windows silence exactly sixteen proposal attempts."""
    p = core["SuffixLookup"]()
    context = list(range(12)) + [99] + list(range(9))
    assert p.propose(context, 15)
    for _ in range(4):
        p.observe(3, 0)
    assert all(p.propose(context, 15) == [] for _ in range(16))
    assert p.propose(context, 15)


@pytest.mark.parametrize(
    "case,want",
    list(
        zip(
            [
                json.loads(x)
                for x in (DATA / "feedback-input.jsonl").read_text().splitlines()
            ],
            [
                json.loads(x)
                for x in (DATA / "feedback-expected.jsonl").read_text().splitlines()
            ],
            strict=True,
        )
    ),
)
def test_feedback_matches_native_round_observation(case, want):
    rule = core["LaneRule"](costs=dict(enumerate(case["costs"], 1)))
    if case["before"] is not None:
        rule.overhead[1] = case["before"]
    rule.observe_round(case["kind"], case["drafts"], case["ms"], case["initializing"])
    assert rule.overhead_ms(1) == pytest.approx(want["overhead"], rel=1e-14, abs=1e-12)
    if want["cost"] is None:
        assert case["drafts"] not in rule.measured_cost
    else:
        assert rule.measured_cost[case["drafts"]] == pytest.approx(want["cost"])
